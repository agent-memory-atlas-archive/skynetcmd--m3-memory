#!/usr/bin/env python3
"""Generate m3's configuration docs and the shipped default config from the registry.

    python bin/gen_config_docs.py

Writes, all from ``m3_core.config.REGISTRY`` (never hand-edited):
  * docs/CONFIG_REFERENCE.md and docs/schema/m3_config.schema.json;
  * bin/m3_core/config/default-m3_config.toml, the file m3 copies into a config
    root that has no m3_config.toml (``m3_core.config.default_file`` renders it),
    and its SHA-256 in bin/m3_core/config/_default_config_sha256.py, which m3
    checks before copying;
  * docs/ENVIRONMENT_VARIABLES.md: the environment names m3 still reads by
    design, every legacy name of a setting with the key it moved to, and the
    retired names.
tests/test_generated_docs_fresh.py fails when the registry moves without them.
"""

from __future__ import annotations

import json
import os
import sys

_BIN = os.path.dirname(os.path.abspath(__file__))
if _BIN not in sys.path:
    sys.path.insert(0, _BIN)

from m3_core.atomic_io import atomic_write  # noqa: E402
from m3_core.config import (  # noqa: E402
    REGISTRY,
    KeyClass,
    default_file,  # noqa: E402
)
from m3_core.config.keys import NOT_SETTINGS, RETIRED  # noqa: E402
from m3_core.config.loader import CONFIG_FILE_NAME, SCHEMA_VERSION, show_key  # noqa: E402
from m3_core.config.registry import Key, Scope, choices_of, type_name  # noqa: E402
from m3_core.config.stores import LEGACY_LOCATORS  # noqa: E402

_ROOT = os.path.dirname(_BIN)
OUTPUT = os.path.join(_ROOT, "docs", "CONFIG_REFERENCE.md")
SCHEMA_OUTPUT = os.path.join(_ROOT, "docs", "schema", "m3_config.schema.json")
ENV_OUTPUT = os.path.join(_ROOT, "docs", "ENVIRONMENT_VARIABLES.md")
DEFAULT_OUTPUT = os.path.join(_BIN, "m3_core", "config", default_file.DEFAULT_FILE_NAME)
SHA_OUTPUT = os.path.join(_BIN, "m3_core", "config", "_default_config_sha256.py")

_CONFIG_ROOT_PRECEDENCE = (
    f"The file is `{CONFIG_FILE_NAME}` in the config root (`--config <file>` > "
    "`M3_CONFIG_ROOT` > `M3_MEMORY_ROOT/config` (legacy) > `~/.m3/config`)."
)

_JSON_TYPE = {
    "boolean": "boolean",
    "integer": "integer",
    "number": "number",
    "string": "string",
    "path": "string",
    "list of strings": "array",
}


def _default(key: Key) -> str:
    if key.default is None:
        return "(none)"
    return f"`{json.dumps(key.default) if not isinstance(key.default, str) else key.default}`"


def _cell(text: str) -> str:
    # "<" escaped: GitHub drops an unknown tag, so "<memory_root>/engine" rendered as "/engine".
    return text.replace("|", "\\|").replace("\n", " ").replace("<", "&lt;")


def render_markdown() -> str:
    lines = [
        "# m3_config.toml reference",
        "",
        "<!-- GENERATED by bin/gen_config_docs.py from the config registry. Do not edit. -->",
        "",
        f"{_CONFIG_ROOT_PRECEDENCE} It carries `schema_version = {SCHEMA_VERSION}`. When the config "
        f"root has none, `m3 setup`, `m3 upgrade` and `m3 config import-env` create it from "
        f"`{default_file.DEFAULT_FILE_NAME}`, which lists every key below commented at its default.",
        "",
        "Precedence for each setting: the environment, for the keys marked *env override* "
        "only; then this file; then, through release N+3, the setting's legacy environment "
        "names; then `.env`; then, for the `[llm]` keys, `.llm_config.json`; then the default. "
        "`m3 config show --origin` prints where each value came from; `m3 config set KEY VALUE` "
        "and `m3 config unset KEY` change this file; `m3 config import-env` moves settings "
        "from the environment, rc files, `.env` and MCP env blocks into it.",
        "",
        "**N+3**, here and in m3's messages: N is release 2026.10.17.0, the first with this "
        "file. Legacy names keep working, with a warning, through the third release after it "
        "(N+3) and stop being read in the release after that.",
        "",
    ]
    for table, keys in sorted(REGISTRY.tables().items()):
        lines += [f"## [{table}]", "", "| Key | Type | Default | Deprecated environment names | Notes |", "|---|---|---|---|---|"]
        for key in sorted(keys, key=lambda k: k.leaf):
            notes = []
            if not key.reloadable:
                notes.append("restart to apply")
            if (ch := choices_of(key)) is not None:
                notes.append("one of " + ", ".join(f"`{c}`" for c in ch))
            if key.deprecated:
                notes.append(f"deprecated: {key.deprecated}")
            notes.append(_cell(key.doc))
            env = ", ".join(f"`{n}`" for n in key.env_names) or "(none)"
            lines.append(f"| `{key.leaf}` | {type_name(key)} | {_default(key)} | {env} | {'; '.join(notes)} |")
        lines.append("")
    secrets = sorted((k for k in REGISTRY if k.klass is KeyClass.SECRET), key=lambda k: k.name)
    lines += [
        "## Secrets",
        "",
        "Secrets are never read from this file, or from the environment. Each resolves from "
        "the user-only secrets file (`[secrets].file`), then the OS keyring entry that file "
        'names (`NAME = { keyring = "service/key" }`, or `system/NAME` when it does not list '
        "the name), then the encrypted vault, except a *bootstrap* secret, which never comes "
        "from the vault. Store one with `m3 secret set NAME` (add `--keyring` for the OS "
        "keyring, or `--stdin` to read the value from a script's standard input); "
        "`m3 config import-env` moves the ones set in the older places.",
        "",
        "| Name | Older environment names (`import-env` reads them) | Bootstrap | Notes |",
        "|---|---|---|---|",
    ]
    for key in secrets:
        env = ", ".join(f"`{n}`" for n in key.env_names)
        lines.append(f"| `{key.name}` | {env} | {'yes' if key.bootstrap else 'no'} | {_cell(key.doc)} |")
    return "\n".join(lines) + "\n"


def render_schema() -> dict:
    tables: dict[str, dict] = {}
    for table, keys in sorted(REGISTRY.tables().items()):
        props = {}
        for key in sorted(keys, key=lambda k: k.leaf):
            tname = type_name(key)
            prop: dict = {"type": _JSON_TYPE[tname], "description": key.doc}
            if tname == "list of strings":
                prop["items"] = {"type": "string"}
            if (ch := choices_of(key)) is not None:
                prop["enum"] = list(ch)
            if key.default is not None and not hasattr(key.default, "__fspath__"):
                prop["default"] = key.default
            props[key.leaf] = prop
        node: dict = tables
        parts = table.split(".")
        for part in parts[:-1]:
            node = node.setdefault(part, {"type": "object", "additionalProperties": False, "properties": {}})[
                "properties"
            ]
        node[parts[-1]] = {"type": "object", "additionalProperties": False, "properties": props}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "m3_config.toml",
        "description": "Generated by bin/gen_config_docs.py from the m3 config registry.",
        "type": "object",
        "additionalProperties": False,
        "properties": {"schema_version": {"type": "integer", "minimum": 1}, **tables},
    }


def render_sha_module(default_text: str) -> str:
    return (
        f'"""GENERATED by bin/gen_config_docs.py from {default_file.DEFAULT_FILE_NAME}. Do not edit.\n'
        "\n"
        "The SHA-256 of the shipped default config's content (line endings read as LF),\n"
        "checked by m3_core.config.default_file before m3 copies the file into a config root.\n"
        '"""\n'
        "\n"
        f'SHA256 = "{default_file.digest(default_text.encode("utf-8"))}"\n'
    )


def _other_programs_names() -> list[str]:
    """The env gate's allow-list of OS and other programs' names: its one owner."""
    import check_env_access

    return sorted(check_env_access.OS_NAMES, key=str.lower)


def _anchor_heading(title: str) -> list[str]:
    return [f"## {title}", ""]


def render_env_markdown() -> str:
    """docs/ENVIRONMENT_VARIABLES.md: what m3 still reads from the environment,
    where each legacy name of a setting went, and which names are retired."""
    config_keys = sorted((k for k in REGISTRY if k.klass is KeyClass.CONFIG), key=lambda k: k.name)
    locators = [k for k in config_keys if k.scope is Scope.LOCATOR and k.env_names]
    secrets = sorted((k for k in REGISTRY if k.klass is KeyClass.SECRET), key=lambda k: k.name)
    lines = [
        "# Environment variables",
        "",
        "<!-- GENERATED by bin/gen_config_docs.py from the config registry. Do not edit. -->",
        "",
        f"m3's settings live in `{CONFIG_FILE_NAME}` ([reference](CONFIG_REFERENCE.md)) and its "
        "secrets in the user-only secrets file. The environment is left with three jobs: saying "
        "where m3's files are (the locators), a few switches and handoffs that are read before any "
        "configuration loads, and other programs' own variables. Every other name below is a "
        f"**legacy name** of a setting: m3 still reads it, below `{CONFIG_FILE_NAME}`, through release "
        "N+3, and `m3 doctor` and `m3 config import-env` name any still set.",
        "",
        f"`m3 config import-env` moves them into `{CONFIG_FILE_NAME}` (and secrets into the secrets "
        "file) from the environment, shell startup files, `.env` files, the Windows persistent "
        "environment and agents' MCP `env` blocks. `m3 setup` and `m3 upgrade` run it, after "
        f"creating `{CONFIG_FILE_NAME}` from `{default_file.DEFAULT_FILE_NAME}` when the config root "
        "has none. It never edits the places it reads from; remove the old copies yourself. "
        "`m3 config show --origin` prints where each value came from.",
        "",
        "- [Variables m3 reads by design](#variables-m3-reads-by-design)",
        "- [Settings: environment name to config key](#settings-environment-name-to-config-key)",
        "- [Secrets: environment name to secrets file](#secrets-environment-name-to-secrets-file)",
        "- [Retired: no effect](#retired-no-effect)",
        "",
        *_anchor_heading("Variables m3 reads by design"),
        "### Roots and locators",
        "",
        "A locator says where m3's files are, so it is read before any configuration loads. "
        f"{_CONFIG_ROOT_PRECEDENCE} `M3_MEMORY_ROOT` is the legacy master root: set alone, the "
        "other roots derive from it unless their own name is set. No locator is required; each "
        "has a working default.",
        "",
        "| Name | Config key | What it locates |",
        "|---|---|---|",
        f"| `M3_CONFIG_ROOT` | (none) | {_cell(NOT_SETTINGS['M3_CONFIG_ROOT'])} |",
    ]
    for key in locators:
        for env in key.env_names:
            lines.append(f"| `{env}` | `{show_key(key.name)}` | {_cell(key.doc)} |")
    lines += [
        "",
        "**Deprecated.** m3 reads one variable, `M3_CONFIG_ROOT`, and takes every root from "
        "`m3_config.toml` (the `paths.*` keys above). These names still work, below the file, and "
        "`m3 doctor` lists any still set, with the `m3 config set` that replaces each. Set "
        "`M3_CONFIG_ROOT` only for a config root other than `~/.m3/config`, and then everywhere m3 "
        "runs: an agent's MCP server reads it from its registration's `env` block (for Claude Code, "
        "`~/.claude.json`), the chatlog hooks from the agent's process environment.",
        "",
        "### Not settings",
        "",
        "Read by m3 by design, and never a key in the file:",
        "",
        "| Name | Why it stays an environment variable |",
        "|---|---|",
    ]
    lines += [f"| `{n}` | {_cell(why)} |" for n, why in sorted(NOT_SETTINGS.items()) if n != "M3_CONFIG_ROOT"]
    lines += [
        "",
        "### Legacy store locations",
        "",
        "A database path is a locator, not a setting, so `import-env` never moves these. m3 reads "
        "them through release N+3; `m3 doctor` and `m3 config import-env` name where one is set with "
        "its replacement (`--database PATH` or a `[stores.<name>]` table with `--store NAME`; "
        "`--chatlog-db PATH` for the chatlog).",
        "",
        "| Name | What it locates |",
        "|---|---|",
    ]
    lines += [f"| `{n}` | {_cell(what)} |" for n, what in sorted(LEGACY_LOCATORS.items())]
    lines += [
        "",
        "### Other programs' variables",
        "",
        "m3 reads these, and never treats them as its own settings: "
        + ", ".join(f"`{n}`" for n in _other_programs_names())
        + ".",
        "",
        *_anchor_heading("Settings: environment name to config key"),
        f"Each name is a legacy name of the key beside it: set the key in `{CONFIG_FILE_NAME}` "
        "(`m3 config set KEY VALUE`) and remove the variable. A list is comma-separated in the "
        "environment and a TOML array in the file. Rows marked *locator* are also read as "
        "locators (above).",
        "",
        "| Environment name | Section | Key | Notes |",
        "|---|---|---|---|",
    ]
    for key in config_keys:
        notes = []
        if key.scope is Scope.LOCATOR:
            notes.append("locator")
        if key.deprecated:
            notes.append(f"deprecated: {_cell(key.deprecated)}")
        for env in key.env_names:
            lines.append(f"| `{env}` | `[{key.table}]` | `{key.leaf}` | {'; '.join(notes)} |")
    lines += [
        "",
        *_anchor_heading("Secrets: environment name to secrets file"),
        "**m3 never reads its own secrets from the environment** (or from "
        f"`{CONFIG_FILE_NAME}`, which refuses one). Each resolves from the user-only secrets file "
        "(`[secrets] file`, default `<config root>/m3_secrets.toml`), then the OS keyring entry "
        "that file names, then the encrypted vault, except a bootstrap secret, which never comes "
        "from the vault ([details](CONFIG_REFERENCE.md#secrets)). Store one with "
        "`m3 secret set NAME`, which prompts for the value; never put a secret on a command line. "
        "`m3 config import-env` moves the ones still set in the places above, without showing "
        "their values. A scripted or CI install writes the secrets file rather than exporting "
        "variables for m3.",
        "",
        "| Environment name | Stored as | Bootstrap |",
        "|---|---|---|",
    ]
    for key in secrets:
        for env in key.env_names:
            lines.append(f"| `{env}` | `{key.name}` in the secrets file | {'yes' if key.bootstrap else 'no'} |")
    lines += [
        "",
        *_anchor_heading("Retired: no effect"),
        "These names were settings that changed nothing, and are retired. Setting one has no effect; "
        "`m3 config show` names any that is set.",
        "",
        "| Name | Status | Why |",
        "|---|---|---|",
    ]
    lines += [f"| `{n}` | retired: no effect | {_cell(why)} |" for n, why in sorted(RETIRED.items())]
    return "\n".join(lines) + "\n"


def main() -> int:
    outputs = {
        OUTPUT: render_markdown(),
        SCHEMA_OUTPUT: json.dumps(render_schema(), indent=2) + "\n",
        ENV_OUTPUT: render_env_markdown(),
    }
    default_text = default_file.render()
    outputs[DEFAULT_OUTPUT] = default_text
    outputs[SHA_OUTPUT] = render_sha_module(default_text)
    for path, text in outputs.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        atomic_write(path, text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
