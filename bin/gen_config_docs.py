#!/usr/bin/env python3
"""Generate the m3_config.toml reference and JSON Schema from the config registry.

    python bin/gen_config_docs.py

Writes docs/CONFIG_REFERENCE.md and docs/schema/m3_config.schema.json. Both are
derived from ``m3_core.config.REGISTRY`` and never hand-edited;
tests/test_generated_docs_fresh.py fails when the registry moves without them.
"""
from __future__ import annotations

import json
import os
import sys

_BIN = os.path.dirname(os.path.abspath(__file__))
if _BIN not in sys.path:
    sys.path.insert(0, _BIN)

from m3_core.atomic_io import atomic_write  # noqa: E402
from m3_core.config import REGISTRY, KeyClass  # noqa: E402
from m3_core.config.loader import CONFIG_FILE_NAME, SCHEMA_VERSION  # noqa: E402
from m3_core.config.registry import Key, choices_of, type_name  # noqa: E402

_ROOT = os.path.dirname(_BIN)
OUTPUT = os.path.join(_ROOT, "docs", "CONFIG_REFERENCE.md")
SCHEMA_OUTPUT = os.path.join(_ROOT, "docs", "schema", "m3_config.schema.json")

_JSON_TYPE = {"boolean": "boolean", "integer": "integer", "number": "number",
              "string": "string", "path": "string", "list of strings": "array"}


def _default(key: Key) -> str:
    if key.default is None:
        return "(none)"
    return f"`{json.dumps(key.default) if not isinstance(key.default, str) else key.default}`"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown() -> str:
    lines = [
        "# m3_config.toml reference",
        "",
        "<!-- GENERATED by bin/gen_config_docs.py from the config registry. Do not edit. -->",
        "",
        f"The file is `{CONFIG_FILE_NAME}` in the config root (`--config <file>` > "
        "`M3_CONFIG_ROOT` > `M3_MEMORY_ROOT/config` (legacy) > `~/.m3/config`). It carries "
        f"`schema_version = {SCHEMA_VERSION}`.",
        "",
        "Precedence for each setting: the environment, for the keys marked *env override* "
        "only; then this file; then, until release N+3, the setting's legacy environment "
        "names; then the default. `m3 config show --origin` prints where each value came from.",
        "",
    ]
    for table, keys in sorted(REGISTRY.tables().items()):
        lines += [f"## [{table}]", "",
                  "| Key | Type | Default | Environment names | Notes |",
                  "|---|---|---|---|---|"]
        for key in sorted(keys, key=lambda k: k.leaf):
            notes = []
            if key.env_override:
                notes.append("env override")
            if not key.reloadable:
                notes.append("restart to apply")
            if (ch := choices_of(key)) is not None:
                notes.append("one of " + ", ".join(f"`{c}`" for c in ch))
            if key.deprecated:
                notes.append(f"deprecated: {key.deprecated}")
            notes.append(_cell(key.doc))
            env = ", ".join(f"`{n}`" for n in key.env_names) or "(none)"
            lines.append(f"| `{key.leaf}` | {type_name(key)} | {_default(key)} | {env} | "
                         f"{'; '.join(notes)} |")
        lines.append("")
    secrets = sorted((k for k in REGISTRY if k.klass is KeyClass.SECRET), key=lambda k: k.name)
    lines += [
        "## Secrets",
        "",
        "Secrets are never read from this file. Each resolves from the environment, then the "
        "OS keyring, then the user-only secrets file (`[secrets].file`), then the encrypted "
        "vault, except a *bootstrap* secret, which never comes from the vault.",
        "",
        "| Name | Environment names | Bootstrap | Notes |",
        "|---|---|---|---|",
    ]
    for key in secrets:
        env = ", ".join(f"`{n}`" for n in key.env_names)
        lines.append(f"| `{key.name}` | {env} | {'yes' if key.bootstrap else 'no'} | {_cell(key.doc)} |")
    return "\n".join(lines) + "\n"


def render_schema() -> dict:
    tables: dict[str, dict] = {}
    for table, keys in sorted(REGISTRY.tables().items()):
        props = {}
        for key in sorted(keys, key=lambda k: k.leaf):
            tname = type_name(key)
            prop: dict = {"type": _JSON_TYPE[tname], "description": key.doc}
            if tname == "list of strings":
                prop["items"] = {"type": "string"}
            if (ch := choices_of(key)) is not None:
                prop["enum"] = list(ch)
            if key.default is not None and not hasattr(key.default, "__fspath__"):
                prop["default"] = key.default
            props[key.leaf] = prop
        node: dict = tables
        parts = table.split(".")
        for part in parts[:-1]:
            node = node.setdefault(part, {"type": "object", "additionalProperties": False,
                                          "properties": {}})["properties"]
        node[parts[-1]] = {"type": "object", "additionalProperties": False, "properties": props}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "m3_config.toml",
        "description": "Generated by bin/gen_config_docs.py from the m3 config registry.",
        "type": "object",
        "additionalProperties": False,
        "properties": {"schema_version": {"type": "integer", "minimum": 1}, **tables},
    }


def main() -> int:
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    os.makedirs(os.path.dirname(SCHEMA_OUTPUT), exist_ok=True)
    atomic_write(OUTPUT, render_markdown())
    atomic_write(SCHEMA_OUTPUT, json.dumps(render_schema(), indent=2) + "\n")
    print(f"wrote {OUTPUT}\nwrote {SCHEMA_OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
