#!/usr/bin/env python3
"""Generate requirements.txt: the lane install set, resolved and pinned.

requirements.txt is the install path for machines without uv (pip-only lanes,
`pip install -r requirements.txt`). It is the project's dependencies plus the
`lint` and `test` dependency groups, resolved for every supported platform and
Python (`uv pip compile --universal`) with exact versions, so every lane
installs the same set. Do not edit it by hand.

It is resolved on its own, not exported from uv.lock: the lock also resolves
the optional extras, and crewai's caps would pin older shared packages
(pydantic 2.12.5 where `pip install m3-memory` gets 2.14.0) into every lane.

    python bin/gen_requirements.py           # after changing the declarations
    python bin/gen_requirements.py --upgrade # re-resolve to the newest allowed

tests/test_dependency_sources.py fails when pyproject and this file disagree.
Why each pin is what it is: docs/DEPENDENCY_NOTES.md.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = ROOT / "pyproject.toml"
OUT = ROOT / "requirements.txt"
GROUPS = ("lint", "test")


def declarations_digest(pyproject: Path = PYPROJECT) -> str:
    """SHA-256 of what this file is resolved from: the project's dependencies,
    requires-python and the lane groups. Any edit to them changes it."""
    d = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    inputs = {
        "requires-python": d["project"]["requires-python"],
        "dependencies": d["project"]["dependencies"],
        "groups": {g: d["dependency-groups"][g] for g in GROUPS},
    }
    blob = json.dumps(inputs, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(blob, usedforsecurity=False).hexdigest()


def header(digest: str) -> str:
    return (
        "# GENERATED by `python bin/gen_requirements.py`; do not edit.\n"
        f"# The project's dependencies + dependency groups {', '.join(GROUPS)}, resolved\n"
        "# for every supported platform and Python. Declarations: pyproject.toml.\n"
        "# Pin notes: docs/DEPENDENCY_NOTES.md.\n"
        f"# declarations sha256: {digest}\n"
    )


def render(*, upgrade: bool) -> str:
    uv = shutil.which("uv")
    if uv is None:
        sys.exit("gen_requirements: uv is required; observed: no `uv` on PATH. "
                 "inspect: https://docs.astral.sh/uv/getting-started/installation/")
    with tempfile.TemporaryDirectory() as tmp:
        # uv reads the pins to keep from, and writes its result to, the
        # --output-file. Work on a copy so a failed run leaves OUT untouched.
        work = Path(tmp) / "requirements.txt"
        if OUT.exists() and not upgrade:
            shutil.copyfile(OUT, work)
        cmd = [uv, "pip", "compile", str(PYPROJECT), "--universal", "--no-header",
               "--quiet", "--output-file", str(work)]
        for g in GROUPS:
            cmd += ["--group", g]
        if upgrade:
            cmd.append("--upgrade")
        subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True,
                       text=True, encoding="utf-8")
        body = work.read_text(encoding="utf-8")
    if "==" not in body:
        sys.exit("gen_requirements: uv produced no pins; observed: an empty resolution. "
                 "inspect: uv pip compile pyproject.toml --universal --group lint --group test")
    return header(declarations_digest()) + body


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--upgrade", action="store_true", help="re-resolve to the newest allowed versions")
    args = ap.parse_args()
    try:
        text = render(upgrade=args.upgrade)
    except subprocess.CalledProcessError as e:
        sys.exit(f"gen_requirements: uv pip compile failed; observed: {e.stderr.strip()[-800:]} "
                 "inspect: uv pip compile pyproject.toml --universal --group lint --group test")
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.name} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
