"""The [embed] file m3-embed-server reads. Python is its only
writer; the Rust server never parses m3_config.toml.

The server deserialises ``[embed]`` with serde WITHOUT ``deny_unknown_fields``
(m3-core-rs ``crates/m3-embed-server/src/config.rs:10-22``), so a key it does not
know is dropped without a word. ``render`` therefore emits only the fields in
``SERVER_FIELDS`` and refuses anything else, and only values the registry holds:
gguf, host, port, ctx. The Rust-only knobs (streams, seq_max, n_batch, n_ubatch,
coalesce_ms, max_batch_tokens) keep the server's own defaults until the
registry adopts them (they carry a stated crash risk).

Where the file lives, per OS, is the server's ``default_config_path()``
(config.rs:113-124); ``server_config_path`` mirrors it, cited, because the two
languages cannot share the function.
"""

from __future__ import annotations

import os
from pathlib import Path

from m3_core.seams import is_macos, is_windows

from .keys_embed import EMBED
from .registry import Key
from .settings import Settings
from .toml_render import render_table

# EmbedSection's fields, config.rs:11-21. The test pins this list.
SERVER_FIELDS = (
    "gguf",
    "port",
    "host",
    "streams",
    "ctx",
    "seq_max",
    "n_batch",
    "n_ubatch",
    "coalesce_ms",
    "max_batch_tokens",
)

_BY_NAME: dict[str, Key] = {k.name: k for k in EMBED}
# server field <- registry key
_FROM_REGISTRY: dict[str, Key] = {
    "gguf": _BY_NAME["embed.gguf"],
    "host": _BY_NAME["embed.server.host"],
    "port": _BY_NAME["embed.server.port"],
    "ctx": _BY_NAME["embed.ctx"],
}
assert set(_FROM_REGISTRY) <= set(SERVER_FIELDS)

_HEADER = "Generated by m3 from m3_config.toml [embed]; do not edit (m3 rewrites it).\nRead by m3-embed-server."


def server_values(settings: Settings) -> dict[str, object]:
    """The server's [embed] values from a settings snapshot (None = not set)."""
    out: dict[str, object] = {}
    for field, key in _FROM_REGISTRY.items():
        value = settings[key]
        out[field] = str(value) if isinstance(value, Path) else value
    return out


def render(values: dict[str, object]) -> str:
    unknown = sorted(set(values) - set(SERVER_FIELDS))
    if unknown:
        raise ValueError(
            f"m3-embed-server would silently ignore {', '.join(unknown)}; it reads only {', '.join(SERVER_FIELDS)}"
        )
    return render_table("embed", values, header=_HEADER)


def server_config_path() -> Path:
    """Mirror of m3-embed-server's default_config_path() (config.rs:113-124)."""
    if is_windows():
        return Path(os.environ.get("PROGRAMDATA") or "C:\\ProgramData") / "m3-embed-server" / "config.toml"
    if is_macos():
        return Path.home() / "Library" / "Application Support" / "m3-embed-server" / "config.toml"
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "m3-embed-server" / "config.toml"
