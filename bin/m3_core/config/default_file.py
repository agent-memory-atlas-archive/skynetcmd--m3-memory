"""The shipped default m3_config.toml: its format, its renderer and its integrity check.

``default-m3_config.toml`` sits beside this module, so it ships wherever the
code does (setup.py grafts bin/ into the wheel with every file) and is found
through ``__file__``, the same locator the code itself uses. It is GENERATED by
bin/gen_config_docs.py from the registry: every non-secret key, commented at
its default, with its doc, type and former env names (not read). Its SHA-256 is generated
into ``_default_config_sha256``, which ships with the code; m3 verifies the
file against it before copying it into a config root (writer.create_from_default).

THE owner of the per-key block format: the writer finds a commented default by
``commented_prefix`` (to set a key in place) and restores ``commented_line``
(to unset one), so the renderer and the editor cannot disagree.

The rendering depends on the registry and the constants here only: no path,
home directory, separator or OS fact of the machine that runs the generator
(tests/test_default_config_file.py renders it under each simulated OS).
"""

from __future__ import annotations

import hashlib
import re
import textwrap
from pathlib import Path

from .keys import REGISTRY
from .loader import CONFIG_FILE_NAME, SCHEMA_VERSION
from .registry import Key, KeyClass, Registry, choices_of, type_name
from .toml_render import toml_value

DEFAULT_FILE_NAME = "default-m3_config.toml"
DEFAULT_FILE = Path(__file__).with_name(DEFAULT_FILE_NAME)

# The last metadata line of every key block starts with this; the writer reads a
# key line that follows it as a default it may comment out again on unset.
TYPE_MARK = "# type: "
_WIDTH = 88
_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")
# "Default: X." / "Unset: X;" in a key's doc names its computed default.
_NAMED_DEFAULT = re.compile(r"\b(Default|Unset):\s*(.+?)(?:;|\.\s|\.$|$)")
# "unset keeps ...", "unset: beside ...", "unset = loopback only" (not "...are unset.").
_UNSET_PHRASE = re.compile(r"\bunset\s*[:=]?\s*([\w~<].*?)(?:;|\.\s|\.$|$)")

_HEADER = f"""\
# m3 configuration: {CONFIG_FILE_NAME}

# GENERATED from m3's config registry by bin/gen_config_docs.py. m3 copies it
# into the config root once, when no {CONFIG_FILE_NAME} exists there, and never
# rewrites a file that exists. Every key: docs/CONFIG_REFERENCE.md.
#
# Every setting is listed at its default, COMMENTED OUT. A commented setting
# follows m3's built-in default, so a later release that changes a default still
# reaches you, and the values you set stand out. To set one, remove its leading
# "# " and change the value, or run `m3 config set KEY VALUE`, which does the
# same in place; `m3 config unset KEY` comments it out again.
# `m3 config show --origin` prints every setting and where its value came from.
#
# A value written <like this> has no fixed default: m3 works it out when it runs
# (from a root, the host or another setting). Replace all of it, brackets too,
# if you set one; left as is, the line is not valid TOML and m3 says so.
#
# "env (not read)" lists the environment names a setting answered to before
# this file. m3 does not read them; `m3 doctor` names any still set, to delete.
# When there is no m3_config.toml yet, `m3 setup` / `m3 upgrade` copy their
# values here once; `m3 config import-env` does it on request.
#
# Paths: "~" is your home folder on every OS. Use forward slashes, which work
# on Windows too ("~/m3/engine", "C:/m3/engine"). In double quotes a backslash
# starts an escape, so write a path with backslashes in single quotes:
# 'C:\\m3\\engine'.
#
# Secrets (API keys, DSNs, tokens) never go in this file: m3 refuses one here.
# They live in the user-only secrets file that [secrets] file names (default
# <config root>/m3_secrets.toml); store one with `m3 secret set NAME`.

schema_version = {SCHEMA_VERSION}
"""


def commented_prefix(leaf: str) -> str:
    """The start of a key's commented default line, whatever its value."""
    return f"# {leaf} = "


def computed_placeholder(key: Key) -> str:
    """An OS-neutral ``<...>`` for a key whose default m3 works out at run
    time, taken from the key's own doc (never from this machine)."""
    m = _NAMED_DEFAULT.search(key.doc)
    if m and m.group(1) == "Default":
        return _bracket(m.group(2))
    if m:
        return _bracket("unset: " + m.group(2))
    m = _UNSET_PHRASE.search(key.doc)
    if m:
        return _bracket("unset: " + m.group(1).removeprefix("is "))
    return "<unset>"


def _bracket(text: str) -> str:
    text = text.strip()
    if text.count("(") > text.count(")"):  # the sentence split inside a parenthesis
        text = text[: text.rfind("(")].rstrip()
    # Already starting with "<" (``<logs root>/<task>.log``): not valid TOML as is.
    return text if text.startswith("<") else f"<{text}>"


def commented_line(key: Key) -> str:
    """``# leaf = <default>``: the line that stands for a key the user has not set."""
    if key.default is None:
        return f"{commented_prefix(key.leaf)}{computed_placeholder(key)}  # default (computed)"
    return f"{commented_prefix(key.leaf)}{toml_value(key.default)}"


def _comment(text: str) -> list[str]:
    return textwrap.wrap(
        text,
        width=_WIDTH,
        initial_indent="# ",
        subsequent_indent="# ",
        break_long_words=False,
        break_on_hyphens=False,
    )


def _type_line(key: Key) -> str:
    parts = [type_name(key)]
    if (ch := choices_of(key)) is not None:
        parts.append("one of " + ", ".join(ch))
    if not key.reloadable:
        parts.append("restart to apply")
    if key.deprecated:
        parts.append(f"deprecated: {key.deprecated}")
    return TYPE_MARK + "; ".join(parts)


def _block(key: Key) -> list[str]:
    if not _BARE_KEY.match(key.leaf):
        raise ValueError(f"{key.name}: {key.leaf!r} is not a bare TOML key; the default file cannot list it")
    lines = _comment(key.doc)
    if key.env_names:
        lines += _comment("env (not read): " + ", ".join(key.env_names))
    lines.append(_type_line(key))
    lines.append(commented_line(key))
    return lines


def render(registry: Registry = REGISTRY) -> str:
    """The default file: header, schema_version, then each table of CONFIG keys
    (sorted, as docs/CONFIG_REFERENCE.md) with its keys sorted by name.
    Secrets never appear: they are not CONFIG keys."""
    out = [_HEADER]
    for table, keys in sorted(registry.tables().items()):
        out.append(f"\n[{table}]\n")
        for key in sorted(keys, key=lambda k: k.leaf):
            if key.klass is not KeyClass.CONFIG:  # tables() holds CONFIG keys only; guard the invariant
                raise ValueError(f"{key.name} is a {key.klass} key and never belongs in the default file")
            out.append("\n" + "\n".join(_block(key)) + "\n")
    return "".join(out)


def digest(data: bytes) -> str:
    """SHA-256 of the file's CONTENT: CRLF is read as LF, so a checkout that
    converted line endings (core.autocrlf) still matches the generated hash.
    Outside the FIPS boundary: it detects an edited or damaged shipped file, not
    an attacker (whoever can edit the file can edit the hash module beside it)."""
    return hashlib.sha256(data.replace(b"\r\n", b"\n"), usedforsecurity=False).hexdigest()


class DefaultFileError(ValueError):
    """The shipped default file is missing or is not the one this m3 shipped."""


def verified_text(path: Path | None = None) -> str:
    """The shipped default file's text (LF), after checking its SHA-256 against
    the hash generated beside the code. Raises ``DefaultFileError`` naming the
    file, the expected and found hash prefixes and the fix; reads nothing else."""
    from ._default_config_sha256 import SHA256

    path = path or DEFAULT_FILE
    try:
        data = path.read_bytes()
    except OSError as e:
        raise DefaultFileError(
            f"observed: m3's default config {path} cannot be read ({e.strerror or e}); nothing was written. "
            "fix: reinstall m3 (`m3 upgrade`, or your package manager's reinstall), then run `m3 setup`"
        ) from e
    found = digest(data)
    if found != SHA256:
        raise DefaultFileError(
            f"observed: m3's default config {path} is not the file this m3 shipped "
            f"(SHA-256 expected {SHA256[:12]}..., found {found[:12]}...); nothing was written. "
            "fix: reinstall m3 (`m3 upgrade`, or your package manager's reinstall), then run `m3 setup`"
        )
    return data.replace(b"\r\n", b"\n").decode("utf-8")
