"""Generate the Codex plugin's skills and the Gemini CLI extension's context file
from the one source the Claude Code plugin ships.

Sources (edit these, never the outputs):

  - ``commands/<name>.md``       the Claude Code ``/m3:<name>`` commands
  - ``skills/m3-guide/SKILL.md`` the how-to-use-m3 skill

Outputs:

  - ``plugins/codex/skills/m3-<name>/SKILL.md`` one Codex skill per command, with
    Claude's syntax rendered for Codex (``/m3:<name>`` -> ``$m3-<name>``,
    ``$ARGUMENTS`` -> ``<input>``, ``m3:<tool>`` -> ``<tool>``)
  - ``plugins/codex/skills/m3-guide/SKILL.md`` the guide, verbatim
  - ``GEMINI.md`` the guide's body, which ``gemini-extension.json`` loads as
    context (``contextFileName``)

Run ``python bin/gen_agent_plugins.py`` after editing a source; ``--check``
writes nothing and exits 1 when an output is stale, missing or no longer has a
source (``tests/test_agent_plugins_fresh.py`` runs it).

Output is deterministic and LF-only, so a re-run with no source change is
byte-identical.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMANDS_DIR = ROOT / "commands"
GUIDE = ROOT / "skills" / "m3-guide" / "SKILL.md"
CODEX_SKILLS = ROOT / "plugins" / "codex" / "skills"
GEMINI_MD = ROOT / "GEMINI.md"

# Literal rewrites of Claude-specific wording, applied before the patterns below.
# Each must still match some source: a source edit that removes the text fails the
# run instead of leaving the Codex skill saying "Claude Code".
_CODEX_LITERALS: tuple[tuple[str, str], ...] = (
    ("Claude Code session", "Codex session"),
    ("Claude Code polls `claude-code`", "Codex polls `codex`"),
    ("(`claude-code@<short>`)", "(`codex@<short>`)"),
    ("slash commands", "skills"),
)
_CODEX_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"/m3:([a-z][a-z-]*)"), r"$m3-\1"),  # a command -> the Codex skill mention
    (re.compile(r"`m3:([a-z_]+)"), r"`\1"),  # an MCP tool of the m3 server
)
_INPUT_NOTE = "`<input>` below is the text the user gave with this request."


class SourceError(Exception):
    pass


def _split_frontmatter(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if not text.startswith("---\n"):
        raise SourceError(f"{path.relative_to(ROOT).as_posix()}: no YAML frontmatter (must start with ---)")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise SourceError(f"{path.relative_to(ROOT).as_posix()}: frontmatter is not closed by ---")
    meta: dict[str, str] = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if sep and key.strip():
            meta[key.strip()] = value.strip()
    for required in ("name", "description"):
        if not meta.get(required):
            raise SourceError(f"{path.relative_to(ROOT).as_posix()}: frontmatter has no {required!r}")
    return meta, text[end + len("\n---\n") :].lstrip("\n")


def _codexify(text: str, used: set[str]) -> str:
    for old, new in _CODEX_LITERALS:
        if old in text:
            used.add(old)
            text = text.replace(old, new)
    for pattern, repl in _CODEX_PATTERNS:
        text = pattern.sub(repl, text)
    return text


def _codex_skill(path: Path, used: set[str]) -> str:
    meta, body = _split_frontmatter(path)
    body = _codexify(body, used)
    lead = ""
    if "$ARGUMENTS" in body:
        body = body.replace("$ARGUMENTS", "<input>")
        lead = _INPUT_NOTE + "\n\n"
    src = path.relative_to(ROOT).as_posix()
    return (
        "---\n"
        f"name: m3-{meta['name']}\n"
        f"description: {json.dumps(_codexify(meta['description'], used), ensure_ascii=False)}\n"
        "---\n\n"
        f"<!-- Generated by bin/gen_agent_plugins.py from {src}; edit that file and re-run. -->\n\n"
        f"{lead}{body.rstrip()}\n"
    )


def _gemini_md() -> str:
    _meta, body = _split_frontmatter(GUIDE)
    return (
        "<!-- Generated by bin/gen_agent_plugins.py from skills/m3-guide/SKILL.md; edit that file and re-run.\n"
        "     The m3 Gemini CLI extension (gemini-extension.json) loads this file as context. -->\n\n"
        f"{body.rstrip()}\n"
    )


def build() -> dict[Path, str]:
    """Every output path and its content."""
    out: dict[Path, str] = {}
    used: set[str] = set()
    commands = sorted(COMMANDS_DIR.glob("*.md"))
    if not commands:
        raise SourceError(f"no commands found in {COMMANDS_DIR}")
    for path in commands:
        out[CODEX_SKILLS / f"m3-{path.stem}" / "SKILL.md"] = _codex_skill(path, used)
    unused = [old for old, _new in _CODEX_LITERALS if old not in used]
    if unused:
        raise SourceError(
            "these Codex rewrites match no source any more, so the Codex skills may keep Claude wording: "
            f"{unused}. Update _CODEX_LITERALS in bin/gen_agent_plugins.py"
        )
    out[CODEX_SKILLS / "m3-guide" / "SKILL.md"] = GUIDE.read_text(encoding="utf-8").replace("\r\n", "\n")
    out[GEMINI_MD] = _gemini_md()
    return out


def _orphans(outputs: dict[Path, str]) -> list[Path]:
    """Skill folders in the Codex plugin that no source produces any more."""
    # os.path: Path.is_dir raises on Python 3.12/3.13 for some paths (test_python_version_seam).
    if not os.path.isdir(CODEX_SKILLS):
        return []
    wanted = {p.parent for p in outputs if p.parent.parent == CODEX_SKILLS}
    return sorted(d for d in CODEX_SKILLS.iterdir() if os.path.isdir(d) and d not in wanted)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the Codex plugin skills and GEMINI.md from their sources.")
    ap.add_argument("--check", action="store_true", help="Write nothing; exit 1 if any output is stale.")
    args = ap.parse_args(argv)
    try:
        outputs = build()
    except (SourceError, OSError) as e:
        print(f"gen_agent_plugins: {e}", file=sys.stderr)
        return 1
    stale: list[str] = []
    for path, text in outputs.items():
        rel = path.relative_to(ROOT).as_posix()
        try:
            # A core.autocrlf checkout holds the committed LF file as CRLF: the same file.
            current = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        except (OSError, UnicodeDecodeError):
            current = None
        if current == text:
            continue
        if args.check:
            stale.append(f"{rel}: {'missing' if current is None else 'stale'}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {rel}")
    for d in _orphans(outputs):
        rel = d.relative_to(ROOT).as_posix()
        if args.check:
            stale.append(f"{rel}: no source produces it")
            continue
        shutil.rmtree(d)
        print(f"removed {rel} (no source produces it)")
    if stale:
        print("agent plugin files out of date (run `python bin/gen_agent_plugins.py`):")
        for s in stale:
            print(f"  {s}")
        return 1
    if args.check:
        print(f"agent plugin files current ({len(outputs)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
