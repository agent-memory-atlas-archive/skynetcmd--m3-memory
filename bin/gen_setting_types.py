#!/usr/bin/env python3
"""Generate m3_memory/_setting_types.py: the static type of ``setting(name)``.

``settings.setting(name)`` returns whatever the registry key holds, so its declared
return type is the union of every value type, and each converted call site lost
its type (190 mypy errors at 2026-10-11). The registry already knows each key's
parser and default; this turns that into ``Literal`` overloads, one per
(type, nullable) group, so ``setting("search.row_cap")`` is ``int`` with no call
site changed. The generated module is stdlib-only, so both accessors take their
signature from it: ``m3_core.config.settings.setting`` and the installed package's
``m3_memory._config.setting``. tests/test_generated_docs_fresh.py fails when it
drifts from the registry.

Usage: python bin/gen_setting_types.py
"""

from __future__ import annotations

import json
import os
import sys
import typing
from pathlib import Path

_BIN = os.path.dirname(os.path.abspath(__file__))
if _BIN not in sys.path:
    sys.path.insert(0, _BIN)

from m3_core.atomic_io import atomic_write  # noqa: E402
from m3_core.config import REGISTRY  # noqa: E402
from m3_core.config.registry import Key, known_type  # noqa: E402

_ROOT = os.path.dirname(_BIN)
OUTPUT = os.path.join(_ROOT, "m3_memory", "_setting_types.py")

# registry.type_name -> the Python type a parsed value has. A parser outside this
# map (a key's own parser) types as the full union: never narrower than the truth.
_PY_TYPE = {
    "boolean": "bool",
    "integer": "int",
    "number": "float",
    "string": "str",
    "path": "Path",
    "list of strings": "list[str]",
}
_UNION = "str | int | float | bool | Path | list[str]"

_HEADER = '''"""GENERATED by bin/gen_setting_types.py from the config registry. Do not edit.

The static type of ``setting(name)``: one overload per value type, so a registry
key's value is typed by its parser (and ``| None`` when it has no default). Typing
only: ``m3_core.config.settings`` and ``m3_memory._config`` import ``setting`` from
here under ``TYPE_CHECKING`` and define the real one themselves.
"""

from __future__ import annotations

from pathlib import Path
from typing import Literal, overload
'''


_ANNOTATED: dict[object, str] = {
    str: "str",
    int: "int",
    float: "float",
    bool: "bool",
    Path: "Path",
    list[str]: "list[str]",
}


def _annotated(parse) -> str | None:
    """A key's own parser, typed by its return annotation when that is one of the
    value types; None (the full union) when it is unannotated or anything else."""
    try:
        ret = typing.get_type_hints(parse).get("return")
    except Exception:  # noqa: BLE001 — a builtin or an unresolvable hint: no claim
        return None
    try:
        return _ANNOTATED.get(ret)
    except TypeError:  # an unhashable annotation
        return None


def _py_type(key: Key) -> str:
    known = known_type(key)
    base = _PY_TYPE[known] if known else (_annotated(key.parse) or _UNION)
    return f"{base} | None" if key.default is None else base


def render() -> str:
    groups: dict[str, list[str]] = {}
    for key in sorted(REGISTRY, key=lambda k: k.name):
        groups.setdefault(_py_type(key), []).append(key.name)
    out = [_HEADER]
    overloads = []
    # Aliases first, then every overload: mypy needs the @overload defs CONSECUTIVE
    # (an assignment between them ends the chain). Shapes follow ruff-format, so
    # the generated file is format- and lint-clean as written.
    for i, (ret, names) in enumerate(sorted(groups.items())):
        alias = f"_Names{i}"
        if len(names) == 1:
            out.append(f"\n{alias} = Literal[{json.dumps(names[0])}]\n")
        else:
            body = "".join(f"    {json.dumps(n)},\n" for n in names)
            out.append(f"\n{alias} = Literal[\n{body}]\n")
        overloads.append(f"\n\n@overload\ndef setting(name: {alias}) -> {ret}: ...\n")
    out.extend(overloads)
    out.append(f"\n\n@overload\ndef setting(name: str) -> {_UNION} | None: ...\n")
    out.append(
        "\n\ndef setting(name: str) -> object:\n"
        '    raise NotImplementedError("typing only: the accessor lives in m3_core.config.settings")\n'
    )
    return "".join(out)


def main() -> int:
    atomic_write(OUTPUT, render())
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
